/**
 * Netlist similarity — adopted from Microsoft SchGen (plan §7).
 *
 * This is the one measurement SchGen has that this pipeline did not, and it is worth
 * taking wholesale. SchGen scores a generated schematic by comparing its **net sets**
 * against a reference design: Jaccard over the connection sets, plus precision/recall/F1
 * in the generated→reference direction (`modules/utils/netlist_comparison_new.py`,
 * reported by `evaluation/eval.py` as `mean_netlist_jaccard` / `mean_netlist_f1`).
 *
 * Why it matters here: every other gate in this ladder is a *property* check — does it
 * lint, route, hold 3.3 V, meet the fab's annular ring. None of them answers "is this
 * the circuit we asked for". Two completely different boards can both be DRC-clean.
 * Comparing against a known-good reference is the only cheap way to catch a generator
 * that has quietly drifted into designing something else.
 *
 * Its limit, stated as plainly as SchGen's own docs do: **it needs a reference.** For a
 * novel board there is nothing to compare to, which is why this is a *regression*
 * metric over the golden set, never a gate on new designs (plan §7.5).
 *
 * The comparison is structural, not name-based: nets are compared by the set of
 * `component.pin` endpoints they join, so `N$12` matching `N$7` is a match if they
 * connect the same pins. That is deliberate — autogenerated net names carry no meaning
 * and a name-sensitive metric would score a correct board as wrong.
 */
import type { NetSummary } from "../types.ts"

export interface NetlistSimilarity {
  jaccard: number
  precision: number
  recall: number
  f1: number
  matched: number
  onlyInCandidate: string[]
  onlyInReference: string[]
}

/** A net as a canonical, order-independent key over its pin endpoints. */
function netKey(net: NetSummary): string {
  return [...net.connections]
    .map((c) => c.trim())
    .sort((a, b) => a.localeCompare(b, "en"))
    .join("|")
}

/**
 * Nets joining fewer than two pins carry no connectivity information — an unconnected
 * stub is not evidence of anything, and counting them inflates both sides.
 */
function keySet(nets: NetSummary[]): Map<string, string> {
  const out = new Map<string, string>()
  for (const net of nets) {
    if ((net.connections?.length ?? 0) < 2) continue
    out.set(netKey(net), net.name)
  }
  return out
}

export function compareNetlists(
  candidate: NetSummary[],
  reference: NetSummary[],
): NetlistSimilarity {
  const a = keySet(candidate)
  const b = keySet(reference)

  let matched = 0
  const onlyInCandidate: string[] = []
  for (const [key, name] of a) {
    if (b.has(key)) matched++
    else onlyInCandidate.push(name)
  }
  const onlyInReference: string[] = []
  for (const [key, name] of b) if (!a.has(key)) onlyInReference.push(name)

  const union = a.size + b.size - matched
  const precision = a.size ? matched / a.size : 0
  const recall = b.size ? matched / b.size : 0

  return {
    jaccard: union ? matched / union : 1,
    precision,
    recall,
    f1: precision + recall ? (2 * precision * recall) / (precision + recall) : 0,
    matched,
    onlyInCandidate: onlyInCandidate.sort(),
    onlyInReference: onlyInReference.sort(),
  }
}

export function describeSimilarity(s: NetlistSimilarity): string {
  return [
    `netlist similarity vs reference: jaccard ${s.jaccard.toFixed(3)}, ` +
      `F1 ${s.f1.toFixed(3)} (precision ${s.precision.toFixed(3)}, recall ${s.recall.toFixed(3)})`,
    `  ${s.matched} net(s) identical`,
    s.onlyInCandidate.length ? `  only in candidate: ${s.onlyInCandidate.join(", ")}` : "",
    s.onlyInReference.length ? `  missing vs reference: ${s.onlyInReference.join(", ")}` : "",
  ]
    .filter(Boolean)
    .join("\n")
}
