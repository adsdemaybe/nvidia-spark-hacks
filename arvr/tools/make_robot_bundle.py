def make_robot_ir() -> None:
    write_json(
        BUNDLE_DIR / "robot_ir.json",
        {
            "schema_version": "1.0",
            "robot_id": "fixture_so101",
            "base_link": "base_link",
            "end_effector_frame": "end_effector",
            "links": ROBOT_IR_LINKS,
            "joints": ROBOT_IR_JOINTS,
        },
    )


def make_actuator() -> None:
    write_json(
        BUNDLE_DIR / "actuator.json",
        {
            "schema_version": "1.0",
            # test_arm.urdf has no gripper/finger articulation.
            "joints": [j["name"] for j in ROBOT_IR_JOINTS if j["type"] != "fixed"],
            "gripper": None,
        },
    )


def main() -> None:
    make_robot_urdf_copy()
    make_manifest()
    make_robot_ir()
    make_actuator()
