#!/usr/bin/env python3
"""Generate the fixture SO-101-class robot bundle deterministically (Shadow
Robot Spatial Demonstration Pipeline spec sections 9-11).

    uv run python tools/make_robot_bundle.py

Writes fixtures/spatial-training/robots/so101/{manifest,robot_ir,actuator}.json
and a physical copy of fixtures/robot/test_arm.urdf as robot.urdf.

The copy (not a symlink or shared reference) is deliberate: the old TEACH
pipeline's `ar_datapipe.robot_model.DEFAULT_URDF` keeps pointing at the
original file, untouched, so this new fixture tree can never accidentally
perturb it. `robot_ir.json`'s joint table is hand-authored to exactly mirror
test_arm.urdf (verified by this script's own test, see
tests/test_spatial_providers.py) rather than parsed from the URDF at
generation time — simplest safe choice for a fixture that doesn't change.
"""

from __future__ import annotations

import json
from pathlib import Path

ARVR_ROOT = Path(__file__).resolve().parent.parent
SOURCE_URDF = ARVR_ROOT / "fixtures" / "robot" / "test_arm.urdf"
BUNDLE_DIR = ARVR_ROOT / "fixtures" / "spatial-training" / "robots" / "so101"
PLACEHOLDER_GLB = ARVR_ROOT / "fixtures" / "ar-xr" / "robot.glb"


def write_json(path: Path, obj: object) -> None:
    path.write_text(json.dumps(obj, indent=2) + "\n")
    print(f"wrote {path.relative_to(ARVR_ROOT)}")


def make_robot_urdf_copy() -> None:
    BUNDLE_DIR.mkdir(parents=True, exist_ok=True)
    dest = BUNDLE_DIR / "robot.urdf"
    # The XML declaration (line 1) must be the very first thing in the file
    # -- a comment before it is invalid XML and urdfdom rejects it outright.
    # Insert this note as an XML comment right after that line instead.
    note = (
        "<!-- Physical copy of fixtures/robot/test_arm.urdf, generated by\n"
        "     tools/make_robot_bundle.py. Deliberately a copy, not a shared\n"
        "     reference -- the old TEACH pipeline's DEFAULT_URDF keeps\n"
        "     pointing at the original file, untouched. See STATE.md. -->\n"
    )
    source_lines = SOURCE_URDF.read_text().splitlines(keepends=True)
    xml_decl, rest = source_lines[0], source_lines[1:]
    dest.write_text(xml_decl + note + "".join(rest))
    print(f"wrote {dest.relative_to(ARVR_ROOT)} (copy of {SOURCE_URDF.relative_to(ARVR_ROOT)})")


def make_manifest() -> None:
    write_json(
        BUNDLE_DIR / "manifest.json",
        {
            "schema_version": "1.0",
            "robot_id": "fixture_so101",
            "source": "fixture",
            "robot_ir": "robot_ir.json",
            "urdf": "robot.urdf",
            # No dedicated SO-101 GLB exists yet -- reuse the existing
            # placeholder robot mesh. Visual fidelity for this fixture comes
            # from the procedural ShadowRobot renderer (xr-web), not this
            # file. See STATE.md's judgment-call log for this pivot.
            "visual_glb": "../../../ar-xr/robot.glb",
            "usd": None,
            "base_link": "base_link",
            "end_effectors": ["end_effector"],
        },
    )


